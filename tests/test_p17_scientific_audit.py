"""P17 independent boundary checks, using labelled synthetic test fields only.

The expected values use vector geometry, Decimal arithmetic and whole-domain
shell integrals. They are not generated by the production matching/search code.
These tests establish numerical behavior, not oceanographic field validation.
"""
